func TestVoronoiWithDuplicatePoints(t *testing.T) {
	pts := []Point{{10, 10}, {90, 10}, {50, 90}, {10, 10}, {90, 10}}
	d := New(pts)
	v := d.Voronoi(0, 0, 100, 100)
	inedges := d.Inedges()
	total := 0.0
	for i := range pts {
		ring := v.CellPolygon(i)
		if inedges[i] == -1 {
			if ring != nil {
				t.Errorf("dropped duplicate %d still has a cell %v", i, ring)
			}
			continue
		}
		total += math.Abs(testPolygonArea(ring)) / 2
	}
	if math.Abs(total-10000) > 1e-6 {
		t.Errorf("cells cover %v of the 10000-unit extent", total)
	}
}

func TestVoronoiOfCollinearPointsTiles(t *testing.T) {
	for n := 3; n <= 8; n++ {
		var pts []Point
		for i := 0; i < n; i++ {
			pts = append(pts, Point{float64(i) * 10, 50})
		}
		v := New(pts).Voronoi(0, 0, 100, 100)
		total := 0.0
		for _, c := range v.CellPolygons() {
			total += math.Abs(testPolygonArea(c.Polygon)) / 2
		}
		if math.Abs(total-10000) > 1e-3 {
			t.Errorf("n=%d: collinear cells cover %v of 10000", n, total)
		}
	}
}

