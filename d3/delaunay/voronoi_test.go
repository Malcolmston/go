func TestVoronoiOfTwoPointsIsAHalfPlaneSplit(t *testing.T) {
	// Two points on the x axis: the boundary is the vertical bisector x = 5,
	// and each cell is exactly the half of the extent on its own side.
	d := New([]Point{{2, 0}, {8, 0}})
	v := d.Voronoi(0, -5, 10, 5)
	for i, wantSide := range []float64{2, 8} {
		ring := v.CellPolygon(i)
		if ring == nil {
			t.Fatalf("cell %d is nil", i)
		}
		if a := math.Abs(testPolygonArea(ring)) / 2; math.Abs(a-50) > 1e-9 {
			t.Errorf("cell %d area = %v, want 50", i, a)
		}
		// Every vertex is on the correct side of x = 5, or exactly on it.
		for _, p := range ring {
			if (wantSide < 5 && p.X > 5+1e-12) || (wantSide > 5 && p.X < 5-1e-12) {
				t.Errorf("cell %d has vertex %v on the wrong side of x=5", i, p)
			}
		}
	}
}

func TestVoronoiBoundsAndRenderShapes(t *testing.T) {
	d := New([]Point{{1, 1}, {3, 1}, {2, 3}})
	v := d.Voronoi(0, 0, 4, 4)
	if got, want := v.RenderBounds(), "M0,0h4v4h-4Z"; got != want {
		t.Errorf("RenderBounds() = %q, want %q", got, want)
	}
	xmin, ymin, xmax, ymax := v.Extent()
	if xmin != 0 || ymin != 0 || xmax != 4 || ymax != 4 {
		t.Errorf("Extent() = %v %v %v %v", xmin, ymin, xmax, ymax)
	}
	if v.Delaunay() != d {
		t.Error("Delaunay() did not return the triangulation it was built from")
	}
	for i := 0; i < 3; i++ {
		s := v.RenderCell(i)
		if !strings.HasPrefix(s, "M") || !strings.HasSuffix(s, "Z") {
			t.Errorf("RenderCell(%d) = %q, want a closed subpath", i, s)
		}
	}
	if !strings.HasPrefix(v.Render(), "M") {
		t.Errorf("Render() = %q", v.Render())
	}
}

func TestInvalidExtentPanics(t *testing.T) {
	d := New([]Point{{0, 0}, {1, 1}})
	for _, tc := range [][4]float64{
		{10, 0, 0, 10},
		{0, 10, 10, 0},
		{0, 0, math.NaN(), 10},
	} {
		func() {
			defer func() {
				if recover() == nil {
					t.Errorf("Voronoi%v did not panic", tc)
				}
			}()
			d.Voronoi(tc[0], tc[1], tc[2], tc[3])
		}()
	}
}

